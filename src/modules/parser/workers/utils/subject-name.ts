/**
 * Название предмета из расписания kai.ru в каноническом виде.
 *
 * Предметы уникальны по точному имени, а kai.ru иногда отдаёт то же название
 * с пробелом по краям или двойным пробелом внутри — без нормализации такой
 * вариант стал бы отдельным предметом рядом с настоящим.
 */
export function normalizeSubjectName(name: string | null | undefined): string {
  return (name ?? '').replace(/\s+/g, ' ').trim();
}
